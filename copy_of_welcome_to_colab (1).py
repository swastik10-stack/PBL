def time_to_min(time_val):
    if pd.isna(time_val):
        return np.nan
    try:
        time_str = str(int(time_val)).zfill(4)
        hour = int(time_str[:2])
        minute = int(time_str[2:])
        return hour * 60 + minute
    except ValueError:
        return np.nan


