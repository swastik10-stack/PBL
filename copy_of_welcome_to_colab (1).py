def time_to_min_gradio(time_obj):
    if not time_obj:
        return np.nan
    try:

        time_parts = str(time_obj).split(':')
        hour = int(time_parts[0])
        minute = int(time_parts[1])
        return hour * 60 + minute
    except:
        return np.nan


def predict_delay(input_data):

    input_df = pd.DataFrame([input_data])


    for col, le in encoders.items():
        try:
            input_df[col] = le.transform(input_df[col].astype(str))
        except ValueError:

            input_df[col] = len(le.classes_)

    prediction = model.predict(input_df)
    probability = model.predict_proba(input_df)[:, 1]

    return prediction[0], probability[0]

# Gradio ke liye Wrapper function
def predict_flight_delay(date_str, time_str, airline, origin, destination):

    try:
        fl_date = pd.to_datetime(date_str)
    except:
        return "Error: Invalid Date Format (Use YYYY-MM-DD)"

    fl_time_min = time_to_min_gradio(time_str)

    input_data = {
        'MONTH': fl_date.month,
        'DAY_OF_WEEK': fl_date.dayofweek,
        'SCHED_DEP_MIN': fl_time_min,
        OPERATING_AIRLINE_COL: airline,
        'Origin': origin,
        'Dest': destination
    }

    prediction, probability = predict_delay(input_data)

    prob_percent = probability * 100

    if prediction == 1:
        return f" HIGH RISK OF DELAY (15+ mins)! Probability: {prob_percent:.2f}%"
    else:
        return f" LIKELY ON-TIME! Probability: {(100 - prob_percent):.2f}%"

