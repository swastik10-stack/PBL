# --- Visualization Function (Same as previous fix, just included for completeness) ---
def generate_time_of_day_delay_plot():
    bins = [0, 360, 720, 1080, 1440]
    labels = ['Night (12am-6am)', 'Morning (6am-12pm)', 'Afternoon (12pm-6pm)', 'Evening (6pm-12am)']

    df_temp['TIME_BLOCK'] = pd.cut(df_temp['SCHED_DEP_MIN'], bins=bins, labels=labels, right=False)
    delay_by_time = df_temp.groupby('TIME_BLOCK')[DELAY_MINUTES_COL].mean().reindex(labels)

    fig = plt.figure(figsize=(10, 6))
    sns.barplot(x=delay_by_time.index, y=delay_by_time.values, palette="rocket", hue=delay_by_time.index, legend=False)

    plt.title('Average Flight Delay by Time of Day', fontsize=14)
    plt.ylabel('Average Delay (Minutes)', fontsize=12)
    plt.xlabel('Time Block', fontsize=12)
    plt.xticks(rotation=15, ha='right')
    plt.grid(axis='y', linestyle='--', alpha=0.7)
    plt.tight_layout()
    return fig


